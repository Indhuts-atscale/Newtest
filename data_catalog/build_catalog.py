"""Derive measure -> fact -> dimension -> attribute rows from the SML repo and emit a data catalog dataset.

Usage: python data_catalog/build_catalog.py <repo_root>
Run automatically by .github/workflows/data-catalog.yml whenever the SML changes.
"""
import csv, glob, os, sys, yaml

CATALOG_MODEL = "data_catalog_cube"
CATALOG_DATASET = "data_catalog_relationships"
CONNECTION = os.environ.get("CATALOG_CONNECTION", "con_atscale_as_adventure")

repo = sys.argv[1]


def load_all(folder):
    objs = {}
    for p in sorted(glob.glob(f"{repo}/{folder}/*.yml")):
        d = yaml.safe_load(open(p))
        if isinstance(d, dict) and "unique_name" in d:
            objs[d["unique_name"]] = d
    return objs


def warn(msg):
    print(f"::warning::{msg}")


metrics = load_all("metrics")
dims = load_all("dimensions")
models = [m for n, m in sorted(load_all("models").items())
          if m.get("object_type") == "model" and n != CATALOG_MODEL]


def dim_attributes(dim, join_level):
    """Yield (attr_unique_name, label, type, dataset, key_col) for every attribute in the dimension."""
    by_name = {a["unique_name"]: a for a in dim.get("level_attributes", [])}
    for h in dim.get("hierarchies", []):
        for lvl in h.get("levels", []):
            a = by_name.get(lvl["unique_name"])
            if a is None:
                warn(f"{dim['unique_name']}: level {lvl['unique_name']} has no level_attribute; skipped")
                continue
            kind = "Join Level" if a["unique_name"] == join_level else "Level"
            yield a["unique_name"], a.get("label", a["unique_name"]), kind, a["dataset"], ",".join(a["key_columns"])
            for sa in lvl.get("secondary_attributes", []):
                yield sa["unique_name"], sa.get("label", sa["unique_name"]), "Secondary Attribute", sa["dataset"], ",".join(sa["key_columns"])


rows = []
for model in models:
    for mref in model.get("metrics", []):
        m = metrics.get(mref["unique_name"])
        if m is None:
            # Calculations live in calculations/ and have no fact dataset, so they are not catalogued.
            warn(f"{model['unique_name']}: metric {mref['unique_name']} not found in metrics/; skipped")
            continue
        for rel in model.get("relationships", []):
            if rel["from"]["dataset"] != m.get("dataset"):
                continue
            dim = dims.get(rel["to"]["dimension"])
            if dim is None:
                warn(f"{model['unique_name']}: dimension {rel['to']['dimension']} not found; skipped")
                continue
            for an, al, kind, ds, kc in dim_attributes(dim, rel["to"]["level"]):
                rows.append({
                    "catalog_row_id": str(len(rows) + 1),
                    "model_name": model["unique_name"],
                    "model_label": model.get("label", model["unique_name"]),
                    "measure_name": m["unique_name"],
                    "measure_label": f'{m.get("label", m["unique_name"])} ({m["calculation_method"].title()})',
                    "aggregation": m["calculation_method"],
                    "fact_dataset": m["dataset"],
                    "fact_column": m["column"],
                    "fact_join_key": ",".join(rel["from"]["join_columns"]),
                    "relationship_name": rel["unique_name"].strip(),
                    "dimension_name": dim["unique_name"],
                    "dimension_label": dim.get("label", dim["unique_name"]),
                    "attribute_name": an,
                    "attribute_label": al,
                    "attribute_type": kind,
                    "dimension_dataset": ds,
                    "attribute_key_column": kc,
                })

if not rows:
    sys.exit("No measure -> dimension relationships found; catalog not written.")

cols = list(rows[0])
out = f"{repo}/data_catalog"
os.makedirs(out, exist_ok=True)
with open(f"{out}/data_catalog_relationships.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=cols)
    w.writeheader()
    w.writerows(rows)

q = lambda v: "'" + v.replace("'", "''") + "'"
values = ",\n".join("  (" + ", ".join(q(r[c]) for c in cols) + ")" for r in rows)
sql = f"SELECT * FROM (VALUES\n{values}\n) AS t ({', '.join(cols)})"


class Literal(str):
    pass


yaml.SafeDumper.add_representer(Literal, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|"))
dataset = {
    "unique_name": CATALOG_DATASET,
    "object_type": "dataset",
    "label": "Data Catalog Relationships",
    "description": "One row per model / measure / fact / dimension / attribute path. Generated by data_catalog/build_catalog.py.",
    "connection_id": CONNECTION,
    "sql": Literal(sql),
    "columns": [{"name": c, "data_type": "string"} for c in cols],
}
yaml.safe_dump(dataset, open(f"{repo}/datasets/{CATALOG_DATASET}.yml", "w"), sort_keys=False, width=10000)
print(len(rows), "rows")
